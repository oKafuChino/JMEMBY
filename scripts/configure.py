"""Interactive installer configuration. Never source dotenv as shell code."""
import getpass
import os
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
ENV = ROOT / ".env"


def parse(text):
    result = {}
    for line in text.splitlines():
        if not line or line.lstrip().startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] == "'":
            value = value[1:-1].replace("\\'", "'").replace("\\\\", "\\")
        elif len(value) >= 2 and value[0] == value[-1] == '"':
            raise ValueError("安装脚本仅支持未加引号或单引号 .env 值，请转换后重试")
        result[key.strip()] = value
    return result


def encode(value):
    if any(c in value for c in "\r\n\x00"):
        raise ValueError("配置不能包含换行或 NUL")
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def save(values):
    text = "# Generated by scripts/configure.py; contains credentials.\n"
    text += "".join(f"{key}={encode(value)}\n" for key, value in values.items())
    temporary = ROOT / ".env.install.tmp"
    fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as stream:
        stream.write(text)
    os.chmod(temporary, 0o600)
    temporary.replace(ENV)


def ask(label, default="", secret=False):
    prompt = label + ("（留空保留）" if default else "") + ": "
    value = getpass.getpass(prompt) if secret else input(prompt).strip()
    value = value or default
    if not value:
        raise ValueError(f"{label}不能为空")
    encode(value)
    return value


def main():
    action = sys.argv[1]
    values = parse((ENV if ENV.exists() else ROOT / ".env.example").read_text(encoding="utf-8"))
    if action == "ids":
        uid, gid = values.get("APP_UID", "1000"), values.get("APP_GID", "1000")
        if not uid.isdigit() or not gid.isdigit() or int(uid) <= 0 or int(gid) <= 0:
            raise ValueError("UID/GID 必须为非 root 正整数")
        print(uid, gid)
        return
    if action == "initial":
        if ENV.exists():
            print("检测到现有 .env，保留 Token、部署版本和其他配置。")
            return
        values["TELEGRAM_BOT_TOKEN"] = ask("Telegram Bot Token", secret=True)
        values["TELEGRAM_ALLOWED_USER_IDS"] = ask("允许使用的 Telegram 数字用户 ID，逗号分隔")
        if not re.fullmatch(r"[1-9][0-9]*(,[1-9][0-9]*)*", values["TELEGRAM_ALLOWED_USER_IDS"]):
            raise ValueError("用户 ID 格式无效")
        values["KOMGA_IMAGE"] = "gotson/komga:latest"
        values["KOMGA_PUBLIC_URL"] = ask("Komga 阅读入口", "http://localhost:25600")
    elif action == "komga":
        values["KOMGA_BASE_URL"] = ask("Komga 容器访问地址", values.get("KOMGA_BASE_URL") or "http://komga:25600")
        values["KOMGA_USERNAME"] = ask("Komga 管理员邮箱", values.get("KOMGA_USERNAME", ""))
        values["KOMGA_PASSWORD"] = ask("Komga 管理员密码", values.get("KOMGA_PASSWORD", ""), True)
        old = values.get("KOMGA_LIBRARY_ID", "")
        values["KOMGA_LIBRARY_ID"] = ask("Komga library ID（漫画库页面 URL 中的 ID）", "" if old.startswith("replace") else old)
    else:
        raise ValueError("Unknown action")
    save(values)


if __name__ == "__main__":
    try:
        main()
    except (ValueError, EOFError, KeyboardInterrupt) as exc:
        raise SystemExit(str(exc) or "已取消；未继续部署")
